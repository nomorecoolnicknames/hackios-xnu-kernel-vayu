/*
 * The minimal IOHIDEventService of IOHIDEventService.h: open/close for the event system's user
 * clients, dispatchEvent() for drivers, and the registry properties a HID service publishes.
 * From the Scion kernel's iokit/Kernel/arm/hid/SweetHID.cpp (APSL 2.0), the base class only.
 */
#include <IOKit/IOLib.h>
#include <IOKit/IOService.h>
#include <libkern/c++/OSArray.h>

#include "IOHIDEventService.h"
#include "IOHIDEventServiceUserClient.h"
#include "IOHIDEvent.h"

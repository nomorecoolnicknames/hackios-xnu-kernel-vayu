/* One-shot LE initialization helpers, pure C for the kernel and host tests. */
#ifndef _SYS_VAYU_BT_LEINIT_H_
#define _SYS_VAYU_BT_LEINIT_H_

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#define VAYU_BT_LEINIT_RX_SCAN_COMPLETE    0x01
#define VAYU_BT_LEINIT_RX_RANDOM_COMPLETE  0x02

struct vayu_bt_leinit_rx {
	uint8_t prefix[7], got, seen, calls_left;
	bool active, expired;
};

static inline void
vayu_bt_leinit_rx_reset(struct vayu_bt_leinit_rx *rx)
{
	rx->got = 0;
	rx->seen = 0;
	rx->calls_left = 128;       /* bounded wait even if a reply is lost */
	rx->active = false;
	rx->expired = false;
}

static inline void
vayu_bt_leinit_rx_flush(struct vayu_bt_leinit_rx *rx, uint8_t *out, size_t out_size, size_t *kept)
{
	for (uint8_t i = 0; i < rx->got && *kept < out_size; i++) out[(*kept)++] = rx->prefix[i];
	rx->got = 0;
}

/*
 * Hide only the two Command Complete events generated by our one-shot
 * LE Set Scan Enable(0) and LE Set Random Address commands. All other bytes,
 * including the original LE Set Scan Parameters response, pass unchanged.
 * When both are consumed the filter becomes permanently transparent.
 */
static inline size_t
vayu_bt_leinit_rx_filter(struct vayu_bt_leinit_rx *rx, const uint8_t *bytes, size_t count,
    uint8_t *out, size_t out_size, uint8_t *events, uint8_t *scan_status, uint8_t *random_status)
{
	size_t kept = 0;

	*events = 0;
	if (rx->active && rx->calls_left == 0 && rx->got == 0) {
		/* Expire only at a packet boundary: a partial unrelated event must
		 * never be discarded, and a partial injected CC must resolve first. */
		rx->active = false;
		rx->expired = true;
	} else if (rx->active && rx->calls_left != 0) {
		rx->calls_left--;
	}
	for (size_t i = 0; i < count && kept < out_size; i++) {
		uint8_t byte = bytes[i];

		if (!rx->active) {
			out[kept++] = byte;
			continue;
		}
		if (rx->got == 0 && byte != 0x04) {
			out[kept++] = byte;
			continue;
		}
		rx->prefix[rx->got++] = byte;
		if (rx->got == 1 && rx->prefix[0] != 0x04) {
			vayu_bt_leinit_rx_flush(rx, out, out_size, &kept);
			continue;
		}
		if (rx->got == 2 && rx->prefix[1] != 0x0e) {
			vayu_bt_leinit_rx_flush(rx, out, out_size, &kept);
			continue;
		}
		if (rx->got == 3 && rx->prefix[2] != 0x04) {
			vayu_bt_leinit_rx_flush(rx, out, out_size, &kept);
			continue;
		}
		if (rx->got == 5 && rx->prefix[4] != 0x0c && rx->prefix[4] != 0x05) {
			vayu_bt_leinit_rx_flush(rx, out, out_size, &kept);
			continue;
		}
		if (rx->got == 6 && rx->prefix[5] != 0x20) {
			vayu_bt_leinit_rx_flush(rx, out, out_size, &kept);
			continue;
		}
		if (rx->got != 7) continue;
		if (rx->prefix[4] == 0x0c) {
			rx->seen |= VAYU_BT_LEINIT_RX_SCAN_COMPLETE;
			*events |= VAYU_BT_LEINIT_RX_SCAN_COMPLETE;
			*scan_status = rx->prefix[6];
		} else {
			rx->seen |= VAYU_BT_LEINIT_RX_RANDOM_COMPLETE;
			*events |= VAYU_BT_LEINIT_RX_RANDOM_COMPLETE;
			*random_status = rx->prefix[6];
		}
		rx->got = 0;
		if (rx->seen == (VAYU_BT_LEINIT_RX_SCAN_COMPLETE | VAYU_BT_LEINIT_RX_RANDOM_COMPLETE)) {
			rx->active = false;
		}
	}
	return kept;
}

/* A valid static random address derived from a real public BD_ADDR. */
static inline bool
vayu_bt_leinit_random_address(const uint8_t public_addr[6], uint8_t random_addr[6])
{
	bool zero = true, ones = true, placeholder = true;

	for (unsigned i = 0; i < 6; i++) {
		if (public_addr[i] != 0) zero = false;
		if (public_addr[i] != 0xff) ones = false;
		if (public_addr[i] != (i == 0 ? 0xad : i == 1 ? 0x5a : 0)) placeholder = false;
		random_addr[i] = public_addr[i];
	}
	if (zero || ones || placeholder) return false;
	random_addr[5] |= 0xc0;       /* HCI little-endian: the address MSB is the last octet */
	zero = ones = true;
	for (unsigned i = 0; i < 6; i++) {
		if (random_addr[i] != 0) zero = false;
		if (random_addr[i] != 0xff) ones = false;
	}
	return !zero && !ones;
}

#endif /* _SYS_VAYU_BT_LEINIT_H_ */

#!/usr/bin/env python3
"""
The boot menu's font (boot_menu_font.h): printable ASCII of a PSF2 console font, 16 pixels wide and 32 high.
Made from Terminus Font Bold 32x16 as Debian's console-setup ships it (Lat15-TerminusBold32x16.psf.gz; SIL Open
Font License 1.1, see font-OFL.txt), glyph rows as 16-bit words, the leftmost pixel the highest bit.

  mkfont.py /usr/share/consolefonts/Lat15-TerminusBold32x16.psf.gz > boot_menu_font.h
"""
import gzip, struct, sys

d = gzip.open(sys.argv[1]).read()
magic, ver, hsize, flags, n, gsize, h, w = struct.unpack_from('<8I', d, 0)
assert magic == 0x864ab572 and (w, h) == (16, 32), 'not a 16x32 PSF2 font'
glyph = lambda i: d[hsize + i * gsize:hsize + (i + 1) * gsize]
index = {}
if flags & 1:                                   # the Unicode table: each glyph's code points, 0xff after each
    o, g = hsize + n * gsize, 0
    while g < n and o < len(d):
        end = d.index(b'\xff', o)
        for ch in d[o:end].decode('utf-8', 'replace').split('￾')[0]:
            index.setdefault(ord(ch), g)
        o, g = end + 1, g + 1
print('/* Generated by mkfont.py from %s: Terminus Font, Copyright (c) 2010 Dimitar Toshkov Zhekov, with Reserved'
      % sys.argv[1].rsplit('/', 1)[-1])
print(' * Font Name "Terminus Font"; SIL Open Font License 1.1 (font-OFL.txt). ASCII 0x20..0x7e, 16x32. */')
print('static const uint16_t menu_font[95][32] = {')
for c in range(0x20, 0x7f):
    gl = glyph(index.get(c, c))
    rows = [gl[2 * r] << 8 | gl[2 * r + 1] for r in range(32)]
    print('\t{ ' + ', '.join('0x%04x' % r for r in rows) + ' },  /* %r */' % chr(c))
print('};')
